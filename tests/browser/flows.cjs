const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const base = process.env.SPORTMANADO_TEST_URL;
if (!base || !['127.0.0.1','localhost'].includes(new URL(base).hostname)) throw Error('An isolated localhost fixture server is required.');
const password = process.env.SPORTMANADO_TEST_PASSWORD;
if (!password) throw Error('SPORTMANADO_TEST_PASSWORD required.');
const output = process.env.SPORTMANADO_EVIDENCE_DIR || path.resolve('browser-evidence');

(async()=>{
    await fs.mkdir(output,{recursive:true});
    const browser=await chromium.launch({headless:true});
    const results=[];
    try {
        const participantContext=await browser.newContext({viewport:{width:390,height:844}});
        const participant=await participantContext.newPage();
        await participant.goto(base+'/register/form?role=user');
        await participant.locator('[name=name]').fill('Peserta Uji Browser');
        await participant.locator('[name=email]').fill(`browser.flow.${Date.now()}@example.test`);
        await participant.locator('[name=password]').fill(password);
        await participant.locator('[name=password_confirmation]').fill(password);
        await participant.locator('button[type=submit]').click();
        await participant.waitForURL('**/dashboard');
        results.push('Participant registered and logged in through browser form');
        const note='Mohon informasi akses kursi roda.';
        async function register(event) {
            await participant.goto(base+`/events/${event}/register`);
            await participant.locator('[name=notes]').fill(note);
            await participant.locator('#submit-btn').click();
            await participant.waitForURL(/\/tickets\/\d+$/);
            const url=participant.url();
            return {url,id:url.split('/').at(-1)};
        }
        const automatic=await register(1);
        assert.ok(await participant.locator('body').innerText().then(text=>text.includes(note)));
        assert.ok(await participant.locator('img[alt="QR Code"]').evaluate(image=>image.complete&&image.naturalWidth>0));
        const code=(await participant.locator('p.font-mono').innerText()).trim();
        results.push('Free automatic registration saves notes and displays QR');
        const manual=await register(2);
        assert.ok((await participant.locator('body').innerText()).includes('Menunggu Persetujuan'));
        assert.equal(await participant.locator('img[alt="QR Code"]').count(),0);
        const eoContext=await browser.newContext({viewport:{width:1440,height:900}});
        const eo=await eoContext.newPage();
        await eo.goto(base+'/login');
        await eo.locator('[name=email]').fill('organizer@example.test');
        await eo.locator('[name=password]').fill(password);
        await eo.locator('button[type=submit]').click();
        await eo.waitForURL('**/organizer/dashboard');
        await eo.goto(base+'/organizer/events/2/participants');
        await eo.locator(`form[action$="/participants/${manual.id}/approve"] button`).click();
        await eo.waitForLoadState('load');
        await participant.goto(manual.url);
        assert.equal(await participant.locator('img[alt="QR Code"]').count(),1);
        results.push('Manual approval changes pending ticket to active with QR');
        await eo.goto(base+'/organizer/events/1/scan');
        await eo.locator('#scanner-connect-btn').click();
        const firstResponse=eo.waitForResponse(response=>response.url().endsWith('/validate-qr')&&response.request().method()==='POST');
        await eo.keyboard.type(JSON.stringify({ticket_code:code,event_id:1}),{delay:1});
        await eo.keyboard.press('Enter');
        const first=await firstResponse;
        assert.equal(first.status(),200);
        assert.equal((await first.json()).valid,true);
        await eo.screenshot({path:path.join(output,'scanner-success-desktop.png'),fullPage:true});
        const secondResponse=eo.waitForResponse(response=>response.url().endsWith('/validate-qr')&&response.request().method()==='POST');
        await eo.locator('#manual-input').fill(code);
        await eo.locator('#manual-input').press('Enter');
        const second=await secondResponse;
        assert.equal(second.status(),422);
        assert.equal((await second.json()).valid,false);
        await participant.goto(automatic.url);
        assert.ok((await participant.locator('body').innerText()).includes('Selesai'));
        results.push('Keyboard scanner JSON input marks ticket used; repeat scan rejected');
        const exported=await eoContext.request.get(base+'/organizer/events/1/participants/export');
        assert.equal(exported.status(),200);
        assert.ok((await exported.text()).includes(note));
        results.push('Organizer CSV contains saved participant notes');
        const forbidden=await participantContext.request.get(base+'/organizer/events/1/scan');
        assert.equal(forbidden.status(),403);
        results.push('Participant cannot access organizer scanner');
        await fs.writeFile(path.join(output,'flow-results.json'),JSON.stringify(results,null,2));
        console.log(JSON.stringify({passed:results.length,results},null,2));
    } finally {await browser.close();}
})().catch(error=>{console.error(error.stack);process.exitCode=1;});
