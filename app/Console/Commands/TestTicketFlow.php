<?php

namespace App\Console\Commands;

use App\Models\Event;
use App\Models\Organizer;
use App\Models\Payment;
use App\Models\Ticket;
use App\Models\User;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;

class TestTicketFlow extends Command
{
    protected $signature = 'test:ticket-flow';
    protected $description = 'Run end-to-end ticket flow test: register → QR generate → scan → validate';

    private int $passed = 0;
    private int $failed = 0;

    public function handle(): int
    {
        $this->info('');
        $this->info('╔══════════════════════════════════════════════════════════╗');
        $this->info('║   SPORTMANADO – Ticket Flow End-to-End Test             ║');
        $this->info('╚══════════════════════════════════════════════════════════╝');
        $this->info('');

        // Use a DB transaction so all test data is automatically rolled back
        DB::beginTransaction();

        try {
            // ── Setup ──────────────────────────────────────────────
            $this->info('▸ Setting up test data...');

            $organizerUser = User::create([
                'name'     => 'Test Organizer ' . Str::random(5),
                'email'    => 'test-eo-' . Str::random(5) . '@sportmanado.test',
                'password' => Hash::make('password'),
                'role'     => 'organizer',
            ]);

            $organizer = Organizer::create([
                'user_id'           => $organizerUser->id,
                'organization_name' => 'Test EO ' . Str::random(5),
                'phone'             => '081234567890',
                'description'       => 'Test organizer for automated testing',
                'status'            => 'approved',
            ]);

            $event = Event::create([
                'organizer_id'        => $organizer->id,
                'title'               => 'Test Event – ' . now()->format('Y-m-d H:i:s'),
                'description'         => 'Automated test event',
                'location'            => 'Manado Test Arena',
                'event_date'          => now()->addDays(7),
                'registration_deadline' => now()->addDays(5),
                'max_participants'    => 100,
                'ticket_price'        => 0,
                'category'            => 'Lari',
                'status'              => 'active',
            ]);

            $participantUser = User::create([
                'name'     => 'Test Participant ' . Str::random(5),
                'email'    => 'test-user-' . Str::random(5) . '@sportmanado.test',
                'password' => Hash::make('password'),
                'role'     => 'user',
            ]);

            $this->info('  ✓ Test organizer, event, and participant created');
            $this->info('');

            // ── Test 1: Create ticket (register) ──────────────────
            $ticketCode = strtoupper(Str::random(10));
            $ticket = Ticket::create([
                'user_id'      => $participantUser->id,
                'event_id'     => $event->id,
                'ticket_code'  => $ticketCode,
                'qr_code_path' => null,
                'status'       => 'pending',
            ]);

            $this->assert(
                'T1: Ticket created with status pending',
                $ticket->exists && $ticket->status === 'pending'
            );

            // ── Test 2: Confirm participant (free event → QR auto-generated by model event) ─
            $ticket->update(['status' => 'active']);
            $ticket->refresh();

            $this->assert(
                'T2: Ticket activated and QR code path set',
                $ticket->status === 'active' && $ticket->qr_code_path !== null
            );

            // ── Test 3: QR SVG file exists in storage ──────────────
            $fileExists = Storage::disk('public')->exists($ticket->qr_code_path);
            $this->assert(
                'T3: QR SVG file exists at storage/' . $ticket->qr_code_path,
                $fileExists
            );

            // ── Test 4: QR payload contains correct ticket_code + event_id ─
            $expectedPayload = json_encode([
                'ticket_code' => $ticket->ticket_code,
                'event_id'    => $ticket->event_id,
            ]);
            $this->assert(
                'T4: QR payload structure matches expected (ticket_code + event_id)',
                str_contains($expectedPayload, $ticketCode)
                    && str_contains($expectedPayload, (string)$event->id)
            );

            // ── Test 5: First scan → valid ────────────────────────
            $scanResult = $this->simulateScan($event, $ticketCode);
            $this->assert(
                'T5: First scan returns valid=true',
                $scanResult['valid'] === true
            );

            $ticket->refresh();
            $this->assert(
                'T5b: Ticket status is now "used"',
                $ticket->status === 'used'
            );
            $this->assert(
                'T5c: used_at timestamp is set',
                $ticket->used_at !== null
            );

            // ── Test 6: Double scan → rejected ────────────────────
            $doubleScanResult = $this->simulateScan($event, $ticketCode);
            $this->assert(
                'T6: Double scan returns valid=false (already used)',
                $doubleScanResult['valid'] === false
                    && str_contains($doubleScanResult['message'] ?? '', 'sudah digunakan')
            );

            // ── Test 7: Invalid code → not found ──────────────────
            $invalidResult = $this->simulateScan($event, 'INVALIDCODE99');
            $this->assert(
                'T7: Invalid code returns valid=false (not found)',
                $invalidResult['valid'] === false
                    && str_contains($invalidResult['message'] ?? '', 'tidak ditemukan')
            );

            // ── Test 8: Pending ticket → rejected ─────────────────
            $participantUser2 = User::create([
                'name'     => 'Test Participant 2 ' . Str::random(5),
                'email'    => 'test-user2-' . Str::random(5) . '@sportmanado.test',
                'password' => Hash::make('password'),
                'role'     => 'user',
            ]);
            $pendingCode = strtoupper(Str::random(10));
            Ticket::create([
                'user_id'      => $participantUser2->id,
                'event_id'     => $event->id,
                'ticket_code'  => $pendingCode,
                'status'       => 'pending',
            ]);
            $pendingResult = $this->simulateScan($event, $pendingCode);
            $this->assert(
                'T8: Pending ticket returns valid=false (not active)',
                $pendingResult['valid'] === false
                    && str_contains($pendingResult['message'] ?? '', 'pending')
            );

            // ── Test 9: Sanitized input works ─────────────────────
            $participantUser3 = User::create([
                'name'     => 'Test Participant 3 ' . Str::random(5),
                'email'    => 'test-user3-' . Str::random(5) . '@sportmanado.test',
                'password' => Hash::make('password'),
                'role'     => 'user',
            ]);
            $sanitizeCode = strtoupper(Str::random(10));
            $sanitizeTicket = Ticket::create([
                'user_id'      => $participantUser3->id,
                'event_id'     => $event->id,
                'ticket_code'  => $sanitizeCode,
                'status'       => 'active',  // QR auto-generated via model event
            ]);

            // Input with extra whitespace and special chars
            $dirtyInput = "  " . $sanitizeCode . "\r\n";
            $cleanedCode = strtoupper(preg_replace('/[^A-Za-z0-9\-]/', '', trim($dirtyInput)));
            $sanitizeResult = $this->simulateScan($event, $cleanedCode);
            $this->assert(
                'T9: Sanitized input (with whitespace/newlines) resolves correctly',
                $sanitizeResult['valid'] === true
            );

        } catch (\Exception $e) {
            $this->error('');
            $this->error('💥 Exception: ' . $e->getMessage());
            $this->error('   at ' . $e->getFile() . ':' . $e->getLine());
            $this->failed++;
        } finally {
            DB::rollBack();
            $this->info('');
            $this->info('  🧹 Test data rolled back (no residual records)');
        }

        // ── Summary ────────────────────────────────────────────
        $this->info('');
        $this->info('══════════════════════════════════════════════════════════');
        $total = $this->passed + $this->failed;
        if ($this->failed === 0) {
            $this->info("  ✅ ALL {$total} TESTS PASSED");
        } else {
            $this->error("  ❌ {$this->failed}/{$total} TESTS FAILED");
        }
        $this->info('══════════════════════════════════════════════════════════');
        $this->info('');

        return $this->failed > 0 ? 1 : 0;
    }

    /**
     * Simulate a QR scan by directly calling the validateQr logic.
     * Bypasses HTTP/auth to test the core business logic.
     */
    private function simulateScan(Event $event, string $ticketCode): array
    {
        try {
            return DB::transaction(function () use ($event, $ticketCode) {
                $cleanCode = strtoupper(preg_replace('/[^A-Za-z0-9\-]/', '', trim($ticketCode)));

                $ticket = Ticket::with(['user', 'payment'])
                    ->where('event_id', $event->id)
                    ->where('ticket_code', $cleanCode)
                    ->lockForUpdate()
                    ->first();

                if (!$ticket) {
                    return ['valid' => false, 'message' => 'Tiket tidak ditemukan untuk acara ini.'];
                }

                if ($ticket->status === 'used') {
                    return [
                        'valid'   => false,
                        'message' => 'Tiket ini sudah digunakan.',
                        'used_at' => $ticket->used_at?->format('d/m/Y H:i'),
                    ];
                }

                if ($ticket->status !== 'active') {
                    return [
                        'valid'   => false,
                        'message' => "Status tiket: '{$ticket->status}'. Hanya tiket aktif yang dapat di-scan.",
                    ];
                }

                $ticket->update([
                    'status'  => 'used',
                    'used_at' => now(),
                ]);

                return [
                    'valid'       => true,
                    'message'     => 'Tiket valid! Peserta diperbolehkan masuk.',
                    'ticket_code' => $ticket->ticket_code,
                    'attendee'    => $ticket->user->name,
                    'email'       => $ticket->user->email,
                    'used_at'     => now()->format('d/m/Y H:i'),
                ];
            });
        } catch (\Exception $e) {
            return ['valid' => false, 'message' => 'Error: ' . $e->getMessage()];
        }
    }

    /**
     * Assert a condition and print result.
     */
    private function assert(string $label, bool $condition): void
    {
        if ($condition) {
            $this->info("  ✅ {$label}");
            $this->passed++;
        } else {
            $this->error("  ❌ {$label}");
            $this->failed++;
        }
    }
}
